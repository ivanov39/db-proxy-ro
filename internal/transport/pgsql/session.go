package pgsql

import (
	"bufio"
	"errors"
	"fmt"
	"log/slog"
	"net"
	"sync"
	"time"

	"github.com/jackc/pgx/v5/pgconn"

	"github.com/ivanov39/db-proxy-ro/internal/usecase"
)

// A unit is everything the backend sends up to and including one
// ReadyForQuery: the reply to a simple Query or to an extended-protocol
// pipeline closed by Sync.
type unit struct {
	start   time.Time
	entries []entry
	cur     int  // entry the backend is currently answering
	failed  bool // the backend reported an error
	errMsg  string
	open    bool // the client has not ended the unit yet
}

// entry is one statement execution, kept for the query log.
type entry struct {
	kind string
	sql  string
	rows int64
	err  string
}

// session relays one client connection to one backend connection.
//
// Two goroutines run it: one reads the client, one reads the backend. The
// client side forwards one unit at a time and waits for its ReadyForQuery
// before reading on. That keeps a refusal generated by the proxy in order
// with backend replies, and guarantees the backend watchdog (see
// backendLoop) sees a statement's effects before the next one is sent.
type session struct {
	gate *usecase.Gatekeeper
	log  *slog.Logger
	info usecase.Session

	client  net.Conn
	backend net.Conn
	fromCli frameReader
	fromSrv frameReader
	toSrv   *bufio.Writer

	mu      sync.Mutex
	idle    *sync.Cond
	toCli   *bufio.Writer // guarded by mu
	pending []*unit       // guarded by mu
	// swallow: the proxy has refused something in the current unit and told
	// the client; backend replies are dropped until the unit ends.
	swallow bool
	closed  bool
	cause   error // why the session ended

	statements map[string]string // prepared statement name -> SQL
	portals    map[string]string // portal name -> SQL
}

func newSession(gate *usecase.Gatekeeper, log *slog.Logger, info usecase.Session,
	client net.Conn, cr *bufio.Reader, backend net.Conn) *session {
	s := &session{
		gate: gate, log: log, info: info,
		client: client, backend: backend,
		fromCli:    frameReader{r: cr, max: maxClientMsgLen},
		fromSrv:    frameReader{r: bufio.NewReaderSize(backend, 32<<10), max: maxServerMsgLen},
		toSrv:      bufio.NewWriter(backend),
		toCli:      bufio.NewWriterSize(client, 32<<10),
		statements: make(map[string]string),
		portals:    make(map[string]string),
	}
	s.idle = sync.NewCond(&s.mu)
	return s
}

// greet completes the client's start-up: no password is asked for.
func (s *session) greet(backend *pgconn.HijackedConn) error {
	writeFrame(s.toCli, msgAuthentication, appendUint32(nil, 0))
	for name, value := range backend.ParameterStatuses {
		writeFrame(s.toCli, msgParameterStatus, parameterStatusBody(name, value))
	}
	writeFrame(s.toCli, msgBackendKeyData, append(appendUint32(nil, backend.PID), backend.SecretKey...))
	writeFrame(s.toCli, msgReadyForQuery, []byte{backend.TxStatus})
	return s.toCli.Flush()
}

func (s *session) run() error {
	done := make(chan struct{})
	go func() {
		s.shutdown(s.backendLoop())
		close(done)
	}()
	s.shutdown(s.clientLoop())
	<-done
	return s.cause
}

// shutdown ends the session. The first caller's error is the one reported:
// the other loop then merely fails on a closed connection.
func (s *session) shutdown(cause error) {
	s.mu.Lock()
	if !s.closed {
		s.closed = true
		s.cause = cause
	}
	s.idle.Broadcast()
	s.mu.Unlock()
	s.client.Close()
	s.backend.Close()
}

// clientLoop reads client messages, inspects the ones carrying SQL and
// forwards what is allowed.
func (s *session) clientLoop() error {
	discard := false // a Parse was refused: skip to the next Sync
	for {
		typ, body, err := s.fromCli.next()
		if err != nil {
			return err
		}
		endOfUnit := false

		switch typ {
		case msgTerminate:
			writeFrame(s.toSrv, typ, body)
			return s.toSrv.Flush()

		case msgQuery:
			sql, _ := cstring(body)
			if dec := s.gate.Inspect(s.info, "query", sql); dec.Allowed {
				s.extend(false, entry{kind: "query", sql: sql})
				writeFrame(s.toSrv, typ, body)
			} else {
				s.refuse(dec.Reason)
			}
			endOfUnit = true

		case msgFunctionCall:
			const reason = "the function call protocol is not allowed"
			s.gate.Refuse(s.info, "function_call", "", reason)
			s.refuse(reason)
			endOfUnit = true

		case msgSync:
			discard = false
			s.extend(false)
			writeFrame(s.toSrv, typ, body)
			endOfUnit = true

		case msgParse:
			if discard {
				continue
			}
			name, rest := cstring(body)
			sql, _ := cstring(rest)
			if dec := s.gate.Inspect(s.info, "parse", sql); !dec.Allowed {
				s.tellRefused(dec.Reason)
				discard = true
				continue
			}
			s.statements[name] = sql
			writeFrame(s.toSrv, typ, body)

		case msgBind:
			if discard {
				continue
			}
			portal, rest := cstring(body)
			statement, _ := cstring(rest)
			sql, ok := s.statements[statement]
			if !ok {
				sql = fmt.Sprintf("<prepared statement %q>", statement)
			}
			s.portals[portal] = sql
			writeFrame(s.toSrv, typ, body)

		case msgExecute:
			if discard {
				continue
			}
			portal, _ := cstring(body)
			s.extend(true, entry{kind: "execute", sql: s.portals[portal]})
			writeFrame(s.toSrv, typ, body)

		case msgClose:
			if discard {
				continue
			}
			if len(body) > 0 {
				name, _ := cstring(body[1:])
				if body[0] == 'S' {
					delete(s.statements, name)
				} else {
					delete(s.portals, name)
				}
			}
			writeFrame(s.toSrv, typ, body)

		case msgDescribe, msgFlush, msgCopyData, msgCopyDone, msgCopyFail:
			if discard {
				continue
			}
			writeFrame(s.toSrv, typ, body)

		default:
			return fmt.Errorf("unexpected client message %q", typ)
		}

		if endOfUnit || s.fromCli.r.Buffered() == 0 {
			if err := s.toSrv.Flush(); err != nil {
				return err
			}
		}
		if endOfUnit {
			if err := s.waitIdle(); err != nil {
				return err
			}
		}
	}
}

// extend adds executions to the unit the client is building, starting one if
// needed. It must be called before the matching message is sent to the
// backend. With open=false the unit is complete: the backend will end it
// with ReadyForQuery.
func (s *session) extend(open bool, entries ...entry) {
	s.mu.Lock()
	defer s.mu.Unlock()
	var u *unit
	if n := len(s.pending); n > 0 && s.pending[n-1].open {
		u = s.pending[n-1]
	} else {
		u = &unit{start: time.Now()}
		s.pending = append(s.pending, u)
	}
	u.entries = append(u.entries, entries...)
	u.open = open
}

// refuse answers a whole unit on the proxy's own authority. The refused
// message is replaced with a Sync, so the backend still produces the
// ReadyForQuery that ends the unit, carrying the true transaction status.
func (s *session) refuse(reason string) {
	s.tellRefused(reason)
	s.extend(false)
	writeFrame(s.toSrv, msgSync, nil)
}

// tellRefused sends the refusal to the client. It is called only between
// units or inside the current one, so it cannot interleave with replies to
// earlier requests.
func (s *session) tellRefused(reason string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	// If the backend has already failed the unit being built, it is skipping
	// to the next Sync itself; a second error would confuse the client.
	failed := false
	if n := len(s.pending); n > 0 {
		failed = s.pending[n-1].failed
	}
	if !s.swallow && !failed {
		// 25006 = read_only_sql_transaction
		writeFrame(s.toCli, msgErrorResponse, errorBody("ERROR", "25006", "db-proxy-ro: "+reason))
		s.toCli.Flush()
	}
	s.swallow = true
}

func (s *session) waitIdle() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	for len(s.pending) > 0 && !s.closed {
		s.idle.Wait()
	}
	if s.closed {
		return errors.New("session closed")
	}
	return nil
}

// backendLoop relays backend messages to the client.
func (s *session) backendLoop() error {
	for {
		typ, body, err := s.fromSrv.next()
		if err != nil {
			return err
		}
		if err := s.relay(typ, body); err != nil {
			return err
		}
	}
}

func (s *session) relay(typ byte, body []byte) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	var u *unit
	if len(s.pending) > 0 {
		u = s.pending[0]
	}
	drop := false

	switch typ {
	case msgParameterStatus:
		// Watchdog: PostgreSQL 14+ reports this setting whenever it changes.
		// The guard should make that impossible; if it happens anyway, stop.
		if name, rest := cstring(body); name == readOnlySetting {
			if value, _ := cstring(rest); value != "on" {
				writeFrame(s.toCli, msgErrorResponse, errorBody("FATAL", "25006",
					"db-proxy-ro: the session left read-only mode and was terminated"))
				s.toCli.Flush()
				s.log.Error("session left read-only mode and was terminated", "value", value)
				return fmt.Errorf("backend reported %s=%s", readOnlySetting, value)
			}
		}
	case msgNoticeResponse, msgNotification:

	case msgReadyForQuery:
		if u != nil {
			s.pending = s.pending[1:]
			s.complete(u)
		}
		s.swallow = false
		s.idle.Broadcast()

	default:
		drop = s.swallow
		if u != nil && !drop {
			u.observe(typ, body)
		}
	}

	if !drop {
		if err := writeFrame(s.toCli, typ, body); err != nil {
			return err
		}
	}
	if s.fromSrv.r.Buffered() == 0 {
		return s.toCli.Flush()
	}
	return nil
}

// observe collects per-statement results for the query log.
func (u *unit) observe(typ byte, body []byte) {
	if typ == msgErrorResponse {
		u.failed, u.errMsg = true, errorMessage(body)
	}
	if u.cur >= len(u.entries) {
		return
	}
	e := &u.entries[u.cur]
	switch typ {
	case msgDataRow:
		e.rows++
	case msgCommandComplete, msgEmptyQueryResponse, msgPortalSuspended:
		// A simple Query may hold several statements but is logged as one.
		if e.kind != "query" {
			u.cur++
		}
	}
}

func (s *session) complete(u *unit) {
	elapsed := time.Since(u.start)
	for i, e := range u.entries {
		switch {
		case u.failed && i == u.cur:
			e.err = u.errMsg
		case u.failed && i > u.cur:
			e.err = "not executed: an earlier statement of the pipeline failed"
		}
		s.gate.Completed(s.info, e.kind, e.sql, usecase.Outcome{Duration: elapsed, Rows: e.rows, Error: e.err})
	}
}
